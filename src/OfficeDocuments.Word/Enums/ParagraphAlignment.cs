namespace OfficeDocuments.Word.Enums;

/// <summary>
/// Horizontal alignment of a paragraph's text.
/// </summary>
public enum ParagraphAlignment
{
    /// <summary>
    /// Aligned to the left margin.
    /// </summary>
    Left,
    /// <summary>
    /// Centered between the margins.
    /// </summary>
    Center,
    /// <summary>
    /// Aligned to the right margin.
    /// </summary>
    Right,
    /// <summary>
    /// Stretched to meet both margins.
    /// </summary>
    Justify,
}
